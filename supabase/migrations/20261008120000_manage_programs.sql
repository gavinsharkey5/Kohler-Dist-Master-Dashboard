comment on column public.allowed_users.program_brands is
  'Brand manager: the suppliers this manager may build programs for. NULL = not a brand manager.';

create or replace function public.kdh_is_program_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce((select program_admin from public.allowed_users where email = public.kdh_caller_email()), false);
$$;
revoke all on function public.kdh_is_program_admin() from public;
grant execute on function public.kdh_is_program_admin() to authenticated;

-- the reps / associates who roll up to a name through allowed_users.reports_to
-- (rep -> DM -> VP ...). Names, because that is what reports_to holds.
create or replace function public.kdh_reports_under(p_name text)
returns setof text language sql stable security definer set search_path = public as $$
  with recursive t as (
    select u.name from public.allowed_users u
      where u.reports_to is not null and lower(trim(u.reports_to)) = lower(trim(p_name))
    union
    select u.name from public.allowed_users u join t on lower(trim(u.reports_to)) = lower(trim(t.name))
  )
  select name from t where name is not null;
$$;
revoke all on function public.kdh_reports_under(text) from public;

-- The caller's program scope. team: null = any participant, [] = none;
-- brands: null = any supplier, [] = none. A manager with neither a team nor
-- brands may draft but not submit anything with participants or products.
create or replace function public.kdh_program_scope()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  me record; team text[]; brands text[];
begin
  select * into me from public.allowed_users where email = public.kdh_caller_email();
  if me is null or me.role <> 'manager' then
    return jsonb_build_object('manager', false, 'admin', false, 'team', '[]'::jsonb, 'brands', '[]'::jsonb);
  end if;
  if me.program_admin then
    return jsonb_build_object('manager', true, 'admin', true, 'team', null, 'brands', null, 'name', me.name);
  end if;
  select array_agg(n) into team from public.kdh_reports_under(me.name) n;
  brands := me.program_brands;
  return jsonb_build_object(
    'manager', true, 'admin', false, 'name', me.name,
    'team',   case when team is null and brands is not null then null            -- brand manager: any rep
                   when team is null then '[]'::jsonb else to_jsonb(team) end,
    'brands', case when brands is null and team is not null then null            -- district manager: any supplier
                   when brands is null then '[]'::jsonb else to_jsonb(brands) end);
end $$;
revoke all on function public.kdh_program_scope() from public;
grant execute on function public.kdh_program_scope() to authenticated;

-- everyone a manager may pick from: name, kind (rep / associate / manager),
-- title, reports_to. No emails. Associates = allow-list rows whose Encompass
-- title says so; there is NO associate -> account mapping on the site yet.
create or replace function public.kdh_program_people()
returns table (name text, kind text, title text, reports_to text)
language sql stable security definer set search_path = public as $$
  select u.name,
         case when u.role = 'rep' then 'rep'
              when u.title ~* 'associate|merchandis' then 'associate'
              else 'manager' end,
         u.title, u.reports_to
  from public.allowed_users u
  where public.kdh_is_manager() and u.name is not null
  order by u.name;
$$;
revoke all on function public.kdh_program_people() from public;
grant execute on function public.kdh_program_people() to authenticated;

