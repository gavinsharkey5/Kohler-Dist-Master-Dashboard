-- MANAGE PROGRAMS (2026-10-08). Run AFTER 20261005090000_photo_admin.sql.
-- Idempotent: safe to run more than once.
--
-- Managers create incentives and MPOs through a guided workflow in the Hub
-- (/manage-programs/). Every program is a row in public.programs with one or
-- more VERSIONS of its definition (program_versions.definition, jsonb). The
-- approver -- the one allow-list row with program_admin = true (Gavin) --
-- approves or returns each submitted version; only an approved version is
-- ever shown to participants. Manager-only financial terms live in a
-- SEPARATE table (program_finance) that participants can never select from,
-- so no dollar amount can reach a rep through any query, export or notice.
--
-- WHO may do what is decided HERE, in security-definer functions, never on
-- the page:
--   program_admin (Gavin)      everything: create, edit any, approve, return,
--                              close out. Identified by the flag on his
--                              allow-list row, NOT by name.
--   any manager                create drafts, edit / submit their own drafts.
--   brand manager              a manager with program_brands set: may put ANY
--                              rep in a program, but only products of those
--                              suppliers.
--   district manager           a manager whom reps report to (allowed_users.
--                              reports_to chain): may put only their team in.
--   neither                    may save drafts, but cannot SUBMIT a program
--                              that names participants or products (a missing
--                              assignment never widens access).
--   reps / associates          read only the approved, non-test programs they
--                              are listed in, with no financial terms.
--
-- WHO is the admin / which suppliers a brand manager owns is NOT written here
-- (the repo is public). After running this file, in the SQL Editor:
--   update public.allowed_users set program_admin = true where email = '<gavin>';
--   update public.allowed_users set program_brands = array['Constellation','Lagunitas Brewing Co']
--     where email = '<brand manager>';
-- supabase/seed/program_brands.sql (generated by tools/program_seed.py from the
-- Fusion supplier list) sets program_brands by NAME match -- review it first.
--
-- Product master: supabase/seed/product_master.sql (generated by
-- tools/program_seed.py; product # / name / supplier / family / package only,
-- no customer data) lets the server check that a brand manager's products
-- really belong to their suppliers. Until it is loaded, a brand-limited
-- manager cannot submit (nothing to check against), an unlimited one can.

-- ------------------------------------------------------------ roles
